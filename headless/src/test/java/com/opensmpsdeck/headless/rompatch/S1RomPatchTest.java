package com.opensmpsdeck.headless.rompatch;

import com.opensmpsdeck.headless.rom.BpsPatch;
import com.opensmpsdeck.headless.rom.RomGame;
import com.opensmpsdeck.headless.rom.VerifiedRom;
import org.junit.jupiter.api.Test;

import java.nio.ByteBuffer;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

class S1RomPatchTest {
    private static final HexFormat HEX = HexFormat.of();
    private static final S1RomPatch.Options TITLE = new S1RomPatch.Options(0x8A, false, true);

    @Test void expandsRomAndRemapsBothEnvelopeReferences() {
        byte[] clean = syntheticRom();
        byte[] pcm = {(byte) 129, (byte) 128, (byte) 127};
        var song = song(pcm);
        var result = S1RomPatch.patchVerified(clean, song, new S1RomPatch.Options(0x89, true, true),
                syntheticDriver());
        byte[] rom = result.bytes();
        var words = ByteBuffer.wrap(rom);
        assertEquals(0x100000, rom.length);
        assertEquals(0xFFFFF, words.getInt(0x1A4));
        assertEquals(S1RomPatch.checksum(rom), Short.toUnsignedInt(words.getShort(0x18E)));
        assertEquals(0x80000, words.getInt(0x71ABC));
        assertEquals(0x769FC, words.getInt(0x71AC0));
        assertEquals(0x0089, Short.toUnsignedInt(words.getShort(0x30DE)));
        assertEquals(0x6008, Short.toUnsignedInt(words.getShort(0x318E)));
        assertEquals(0x4E714E71, words.getInt(0x3216));
        assertEquals((byte) 0xFF, rom[rom.length - 1]);
        assertEquals(1, rom[0x8000F]);
        assertEquals(10, rom[0x80014]);
        int psg = words.getInt(0x719A4);
        assertArrayEquals(Arrays.copyOfRange(clean, 0x719A8, 0x719CC), Arrays.copyOfRange(rom, psg, psg + 36));
        assertArrayEquals(new byte[]{7, 6, (byte) 0x80},
                Arrays.copyOfRange(rom, words.getInt(psg + 36), words.getInt(psg + 36) + 3));
        assertArrayEquals(rom, BpsPatch.apply(BpsPatch.encode(clean, rom).bytes(), clean));
        assertEquals(0x7FFFF, ByteBuffer.wrap(clean).getInt(0x1A4));

        assertEquals(0x84, Byte.toUnsignedInt(rom[0x80010]));
        assertEquals(1030, result.report().get("z80CustomDpcmCapacity").getAsInt());
        int stub = words.getInt(0x136E);
        assertEquals("0839000000a1110066f6", HEX.formatHex(rom, stub, stub + 10));
        assertEquals(0xA01BDA, words.getInt(0x71CB6));
        // Apply the generated byte writes and compare all three original entries.
        byte[] driver = Arrays.copyOf(syntheticDriver(), 0x2000);
        for (int at = stub + 10; Short.toUnsignedInt(words.getShort(at)) == 0x13FC; at += 8) {
            driver[words.getInt(at + 4) - 0xA00000] = rom[at + 3];
        }
        assertArrayEquals(Arrays.copyOfRange(driver, 0xD6, 0xEE), Arrays.copyOfRange(driver, 0x1BC6, 0x1BDE));
        assertEquals(0xC6, Byte.toUnsignedInt(driver[0x46]));
        assertEquals(0x1B, driver[0x47]);
        assertEquals(0xF6, Byte.toUnsignedInt(driver[0x1BDE]));
        assertEquals(2, driver[0x1BE0]);
    }

    @Test void documentedChecksumReadsBigEndianWordsThroughDeclaredEnd() {
        byte[] rom = new byte[0x208];
        ByteBuffer.wrap(rom).putInt(0x1A4, 0x205).putShort(0x200, (short) 0xFFFF)
                .putShort(0x202, (short) 0x1234).putShort(0x204, (short) 0x101).putShort(0x206, (short) 0xEEEE);
        assertEquals(0x1334, S1RomPatch.checksum(rom));
    }

    @Test void overBudgetUsesStockWithoutHookingDriver() {
        byte[] synthetic = syntheticRom();
        var result = S1RomPatch.patchVerified(synthetic, song(new byte[2061]), TITLE, syntheticDriver());
        assertArrayEquals(Arrays.copyOfRange(synthetic, 0x136C, 0x1374),
                Arrays.copyOfRange(result.bytes(), 0x136C, 0x1374));
        assertFalse(result.report().getAsJsonArray("approximations").isEmpty());
        var dac = result.report().getAsJsonArray("dacNoteMap").get(0).getAsJsonObject();
        assertEquals("stock", dac.get("kind").getAsString());
        assertTrue(dac.get("distance").getAsDouble() >= 0);
        assertEquals(dac.get("mappedNote").getAsInt(), Byte.toUnsignedInt(result.bytes()[0x80010]));
    }

    @Test void reusesAnExactStockDrumWithoutAHookAndLeavesOptionalSitesAlone() {
        byte[] clean = syntheticRom();
        byte[] kick = new byte[850 * 2];
        Arrays.fill(kick, (byte) 0x80); // With synthetic zero deltas the decoded kick stays at midpoint.
        var result = S1RomPatch.patchVerified(clean, song(kick), new S1RomPatch.Options(0x8A, true, false),
                syntheticDriver());
        var drum = result.report().getAsJsonArray("dacNoteMap").get(0).getAsJsonObject();
        assertEquals("stock", drum.get("kind").getAsString());
        assertTrue(drum.get("exact").getAsBoolean());
        assertEquals(0x81, drum.get("mappedNote").getAsInt());
        assertArrayEquals(Arrays.copyOfRange(clean, 0x136C, 0x1374),
                Arrays.copyOfRange(result.bytes(), 0x136C, 0x1374));
        assertArrayEquals(Arrays.copyOfRange(clean, 0x30DC, 0x321A),
                Arrays.copyOfRange(result.bytes(), 0x30DC, 0x321A));
    }

    @Test void rejectsUnknownRomUnexpectedPatternsAndOversizedBank() {
        byte[] clean = syntheticRom();
        var song = song(new byte[]{0});
        assertThrows(IllegalArgumentException.class, () -> S1RomPatch.patch(clean, song, TITLE));
        clean[0x3216] = 0;
        var mismatch = assertThrows(IllegalArgumentException.class,
                () -> S1RomPatch.patchVerified(clean, song, TITLE, syntheticDriver()));
        assertTrue(mismatch.getMessage().contains("003212"));
        byte[] driver = syntheticDriver();
        driver[0x46] = (byte) 0xFF;
        var driverMismatch = assertThrows(IllegalArgumentException.class,
                () -> S1RomPatch.patchVerified(syntheticRom(), song, TITLE, driver));
        assertTrue(driverMismatch.getMessage().contains("Z80 RAM 0x000044"));
        var large = new S1Song(new byte[32769], 0, Map.of(), Map.of());
        var size = assertThrows(IllegalArgumentException.class,
                () -> S1RomPatch.patchVerified(syntheticRom(), large, TITLE, syntheticDriver()));
        assertTrue(size.getMessage().contains("32769"));
        assertTrue(size.getMessage().contains("32768"));
        assertTrue(size.getMessage().contains("Shorten the song or reduce layering"));
    }

    @Test void patchesVerifiedRetailCartridge() throws Exception {
        String path = System.getenv("OPENSMPSDECK_S1_ROM");
        assumeTrue(path != null && !path.isBlank(), "Set OPENSMPSDECK_S1_ROM to a clean S1 World REV01 image");
        var clean = VerifiedRom.read(RomGame.S1, Path.of(path));
        assertEquals(0xAFC7, S1RomPatch.checksum(clean.bytes()));
        var result = S1RomTarget.TARGET.patch(clean, song(new byte[]{(byte) 131, (byte) 129}), TITLE);
        assertEquals(0x80000, ByteBuffer.wrap(result.bytes()).getInt(0x71AC0));
        assertArrayEquals(result.bytes(), BpsPatch.apply(BpsPatch.encode(clean.bytes(), result.bytes()).bytes(),
                clean.bytes()));
    }

    private static S1Song song(byte[] pcm) {
        // DAC and PSG1, local envelope 17 in the header and custom envelope 42 in F5.
        return new S1Song(HEX.parseHex("0000010101ff001000000013000000118101f2f52a9908f2"), 0,
                Map.of(17, syntheticEnvelope(), 42, new byte[]{7, 6, (byte) 0x80}),
                Map.of(0x81, new S1Song.Dac(pcm, 23)));
    }

    private static byte[] syntheticEnvelope() {
        byte[] envelope = new byte[23];
        envelope[22] = (byte) 0x80;
        return envelope;
    }

    private static byte[] syntheticRom() {
        byte[] rom = new byte[0x80000];
        S1Revision.ROM_SITES.forEach(site -> write(rom, site.offset(), site.expectedHex()));
        var words = ByteBuffer.wrap(rom);
        for (int i = 0; i < S1Revision.PSG_POINTERS.length; i++) {
            words.putInt(0x719A8 + 4 * i, S1Revision.PSG_POINTERS[i]);
            rom[S1Revision.PSG_POINTERS[i]] = (byte) i;
            rom[S1Revision.PSG_POINTERS[i] + S1Revision.PSG_LENGTHS[i] - 1] = (byte) 0x80;
        }
        return rom;
    }

    private static byte[] syntheticDriver() {
        byte[] driver = new byte[0x1BC6];
        S1Revision.DRIVER_SITES.forEach(site -> write(driver, site.offset(), site.expectedHex()));
        return driver;
    }

    private static void write(byte[] target, int offset, String hex) {
        byte[] bytes = HEX.parseHex(hex);
        System.arraycopy(bytes, 0, target, offset, bytes.length);
    }
}
